GUARD = """
CREATE FUNCTION owner_settlements_guard() RETURNS trigger LANGUAGE plpgsql AS
$$ BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.status <> 'draft' THEN
      RAISE EXCEPTION 'Only a draft settlement can be deleted' USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.status <> 'draft' AND
     (NEW.load_revenue, NEW.carrier_share, NEW.owner_gross, NEW.fuel, NEW.driver_pay_run, NEW.other_costs,
      NEW.escrow, NEW.net, NEW.owner_id, NEW.period_start, NEW.period_end, NEW.number, NEW.currency)
     IS DISTINCT FROM
     (OLD.load_revenue, OLD.carrier_share, OLD.owner_gross, OLD.fuel, OLD.driver_pay_run, OLD.other_costs,
      OLD.escrow, OLD.net, OLD.owner_id, OLD.period_start, OLD.period_end, OLD.number, OLD.currency) THEN
    RAISE EXCEPTION 'An approved settlement cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.status IN ('paid', 'void') AND NEW.status <> OLD.status THEN
    RAISE EXCEPTION 'A paid or void settlement is final' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$
"""

LINES_GUARD = """
CREATE FUNCTION owner_settlement_lines_guard() RETURNS trigger LANGUAGE plpgsql AS
$$ DECLARE parent_status text;
BEGIN
  SELECT status INTO parent_status FROM owner_settlements
  WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.settlement_id ELSE NEW.settlement_id END;
  IF parent_status IS NOT NULL AND parent_status <> 'draft' THEN
    RAISE EXCEPTION 'Lines of an approved settlement cannot be changed' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$
"""


